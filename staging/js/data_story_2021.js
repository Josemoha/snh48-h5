/* ========================================================================
   四、AW9 满员守卫（主线①机制，供引擎调用；用户口径）
   ----------------------------------------------------------------------------
   调用时机（引擎接线待补）：月首结算后、任何成员变动落地后。
   规则：AW9 正式成员 9 人（decisions.unitsAW9）。凡因故不在籍
   （status!=='active' && status!=='branch'）的正式成员：立即移出 AW9；
   【修复】分团在册（branch）算在籍——AW9 成团口径「分团在册者兼任不调动」
   （见 engine.setAW9Reserve），刘倩倩（GNZ48 Team NIII 兼任）此前被误判为
   离团触发补位/补选。预备役（decisions.unitsAW9R）中在籍且人气最高者
   自动顶上（pop+2 bond+2，备注登记）；随后总监需重新点将一名预备成员补足
   预备役（pickMode="aw9r21" → UI 弹窗，引擎接线后回收进 unitsAW9R）。
   返回值：补位事件文本数组（空数组=无需补位）。
   ======================================================================== */
STORY.aw9Guard21 = function (st) {
  const out = [];
  const formal = st.decisions && Array.isArray(st.decisions.unitsAW9) ? st.decisions.unitsAW9 : [];
  const reserve = st.decisions && Array.isArray(st.decisions.unitsAW9R) ? st.decisions.unitsAW9R : [];
  if (!formal.length) return out;

  const leave = formal.filter(n => {
    const m = st.members.find(x => x.name === n);
    /* 在籍=active/branch（分团兼任算在籍，同 setAW9Reserve 口径；修复刘倩倩误判离团） */
    return !m || (m.status !== "active" && m.status !== "branch");
  });
  if (!leave.length) return out;

  const promoted = [];
  leave.forEach(name => {
    const pool = reserve
      /* 预备役点将池本部/分团在册皆可选（同 showAw9r21Picker 口径），此处同步认 branch */
      .map(n => ({ n, m: st.members.find(x => x.name === n && (x.status === "active" || x.status === "branch")) }))
      .filter(x => x.m)
      .sort((a, b) => b.m.pop - a.m.pop);
    if (!pool.length) return;   // 预备役无人可补：引擎待接 UI 提示「AW9 缺员，需点将」
    const top = pool[0];
    promoted.push(top.n);
    top.m.pop = Math.min(100, top.m.pop + 2);
    top.m.bond = Math.min(100, top.m.bond + 2);
    top.m.note = (top.m.note ? top.m.note + "；" : "") + "2021 AW9 补位：正式成员空缺，由预备役顶上（按用户口径满员机制）";
    // 名单迁移
    const fi = st.decisions.unitsAW9.indexOf(name);
    if (fi >= 0) st.decisions.unitsAW9.splice(fi, 1, top.n);
    const ri = st.decisions.unitsAW9R.indexOf(top.n);
    if (ri >= 0) st.decisions.unitsAW9R.splice(ri, 1);
  });

  if (promoted.length) {
    out.push("【AW9 满员机制】" + leave.join("、") + " 不再在籍——预备役 " + promoted.join("、") + " 以最高人气顶上。请总监通过「点将预备成员」行动补足预备役名单（引擎接线后开放选人弹窗）。");
  }
  /* 预备役缺口（补位消耗后 < 初始规模）：由 UI.pickMode="aw9r21" 点将补足（引擎接线待补） */
  return out;
};

